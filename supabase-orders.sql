-- SKIN MASH: الطلبات + المخزون + طلبات المنتجات (شغّله مرة واحدة في SQL Editor)
alter table public.products add column if not exists stock int not null default 50;
alter table public.products add column if not exists published boolean not null default true;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  code text not null unique,
  created_at timestamptz not null default now(),
  name text, phone text, whatsapp text, city text, address text,
  items jsonb not null,
  subtotal numeric not null default 0, shipping numeric not null default 0, total numeric not null default 0,
  pay_method text,
  status text not null default 'new' check (status in ('new','processing','shipped','completed','cancelled','returned')),
  cancel_reason text,
  restocked boolean not null default false
);
create table if not exists public.product_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(name) between 2 and 200),
  description text check (char_length(description) <= 1000),
  category text, notes text, customer_name text,
  phone text check (char_length(phone) <= 20),
  image_url text check (char_length(image_url) <= 500),
  status text not null default 'new' check (status in ('new','review','sourced','contacted','archived'))
);
alter table public.orders enable row level security;
alter table public.product_requests enable row level security;
drop policy if exists "admin read orders" on public.orders;
drop policy if exists "anon add request" on public.product_requests;
drop policy if exists "admin all requests" on public.product_requests;
create policy "admin read orders" on public.orders for select to authenticated using (true);
create policy "anon add request" on public.product_requests for insert to anon, authenticated with check (status = 'new');
create policy "admin all requests" on public.product_requests for all to authenticated using (true) with check (true);
grant select on public.orders to authenticated;
grant insert on public.product_requests to anon;
grant select, insert, update, delete on public.product_requests to authenticated;

-- إنشاء طلب من الموقع: الأسعار والمخزون من قاعدة البيانات (لا يُصدَّق السعر القادم من المتصفح)
create or replace function public.create_order(p jsonb) returns text
language plpgsql security definer set search_path = public as $$
declare it jsonb; pr record; q int; sub numeric := 0; shp numeric; lines jsonb := '[]'; c jsonb := p->'customer'; cd text := p->>'code';
begin
  if cd !~ '^SM-[A-Z0-9]{4,10}$' then raise exception 'رقم طلب غير صالح'; end if;
  if jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 or jsonb_array_length(p->'items') > 40 then raise exception 'السلة فارغة'; end if;
  if char_length(coalesce(c->>'phone','')) not between 8 and 20 or char_length(coalesce(c->>'name','')) < 2 then raise exception 'بيانات العميل ناقصة'; end if;
  for it in select * from jsonb_array_elements(p->'items') loop
    q := least(greatest((it->>'qty')::int, 1), 20);
    select id, name, price, stock, published into pr from products where id = (it->>'id')::bigint for update;
    if not found or not pr.published then raise exception 'منتج غير متاح'; end if;
    if pr.stock < q then raise exception 'نفدت الكمية من: %', pr.name; end if;
    update products set stock = stock - q where id = pr.id;
    sub := sub + pr.price * q;
    lines := lines || jsonb_build_array(jsonb_build_object('id', pr.id, 'name', pr.name, 'price', pr.price, 'qty', q));
  end loop;
  shp := least(greatest(coalesce((p->>'shipping')::numeric, 0), 0), 200);
  insert into orders(code, name, phone, whatsapp, city, address, items, subtotal, shipping, total, pay_method)
  values (cd, left(c->>'name',100), c->>'phone', c->>'whatsapp', left(c->>'city',100), left(c->>'address',300), lines, sub, shp, sub + shp, left(p->>'pay_method',20));
  return cd;
end $$;

-- تغيير حالة الطلب (للأدمن فقط) + إرجاع الكميات عند الإلغاء/الإرجاع
create or replace function public.set_order_status(p_id bigint, p_status text, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare o orders; it jsonb;
begin
  if auth.role() <> 'authenticated' then raise exception 'غير مصرح'; end if;
  select * into o from orders where id = p_id for update;
  if not found then raise exception 'الطلب غير موجود'; end if;
  if o.status in ('cancelled','returned') then raise exception 'الطلب مُغلق ولا يمكن تعديله'; end if;
  if p_status in ('cancelled','returned') then
    if coalesce(p_reason,'') = '' then raise exception 'اكتب سبب الإلغاء'; end if;
    for it in select * from jsonb_array_elements(o.items) loop
      update products set stock = stock + (it->>'qty')::int where id = (it->>'id')::bigint;
    end loop;
    update orders set status = p_status, cancel_reason = p_reason, restocked = true where id = p_id;
  else
    update orders set status = p_status where id = p_id;
  end if;
end $$;

revoke all on function public.create_order(jsonb) from public;
revoke all on function public.set_order_status(bigint, text, text) from public;
grant execute on function public.create_order(jsonb) to anon, authenticated;
grant execute on function public.set_order_status(bigint, text, text) to authenticated;

